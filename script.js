const languageToggle = document.querySelector("#languageToggle");
const menuToggle = document.querySelector(".menu-toggle");
const mainNav = document.querySelector("#mainNav");
const pageDescription = document.querySelector('meta[name="description"]');

function getInitialLanguage() {
  try {
    const savedLanguage = localStorage.getItem("stPeterLanguage");
    if (savedLanguage === "fr" || savedLanguage === "en") return savedLanguage;
  } catch (error) {
    // The site still works when browser storage is unavailable.
  }

  const browserLanguage = (navigator.languages && navigator.languages[0]) || navigator.language || "en";
  return browserLanguage.toLowerCase().startsWith("fr") ? "fr" : "en";
}

let currentLanguage = getInitialLanguage();

function applyLanguage(language) {
  currentLanguage = language === "fr" ? "fr" : "en";
  const copy = translations[currentLanguage];

  document.documentElement.lang = currentLanguage === "fr" ? "fr-CA" : "en-CA";
  document.title = copy.pageTitle;
  pageDescription?.setAttribute("content", copy.pageDescription);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (Object.prototype.hasOwnProperty.call(copy, key)) {
      element.innerHTML = copy[key];
    }
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (Object.prototype.hasOwnProperty.call(copy, key)) {
      element.setAttribute("alt", copy[key]);
    }
  });

  languageToggle.textContent = currentLanguage === "fr" ? "EN" : "FR";
  languageToggle.setAttribute("aria-label", copy.languageLabel);
  menuToggle.setAttribute("aria-label", menuToggle.getAttribute("aria-expanded") === "true" ? copy.menuClose : copy.menuOpen);

  try {
    localStorage.setItem("stPeterLanguage", currentLanguage);
  } catch (error) {
    // The selected language remains active until the page is closed.
  }
}

languageToggle.addEventListener("click", () => {
  applyLanguage(currentLanguage === "fr" ? "en" : "fr");
});

function closeMenu() {
  menuToggle.setAttribute("aria-expanded", "false");
  menuToggle.setAttribute("aria-label", translations[currentLanguage].menuOpen);
  mainNav.classList.remove("is-open");
}

menuToggle.addEventListener("click", () => {
  const isOpen = menuToggle.getAttribute("aria-expanded") === "true";
  menuToggle.setAttribute("aria-expanded", String(!isOpen));
  menuToggle.setAttribute("aria-label", isOpen ? translations[currentLanguage].menuOpen : translations[currentLanguage].menuClose);
  mainNav.classList.toggle("is-open", !isOpen);
});

mainNav.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", closeMenu);
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeMenu();
});

document.querySelector("#currentYear").textContent = String(new Date().getFullYear());

if ("IntersectionObserver" in window) {
  const revealObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12, rootMargin: "0px 0px -35px 0px" });

  document.querySelectorAll(".reveal").forEach((element) => revealObserver.observe(element));
} else {
  document.querySelectorAll(".reveal").forEach((element) => element.classList.add("is-visible"));
}

applyLanguage(currentLanguage);
